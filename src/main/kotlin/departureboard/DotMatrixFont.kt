        g('.', ".....", ".....", ".....", ".....", ".....", ".##..", ".##..")
        g(',', ".....", ".....", ".....", ".....", ".##..", "..#..", ".#...")
        g(':', ".....", ".##..", ".##..", ".....", ".##..", ".##..", ".....")
        g(';', ".....", ".##..", ".##..", ".....", ".##..", "..#..", ".#...")
        g('\'', "..#..", "..#..", ".#...", ".....", ".....", ".....", ".....")
        g('"', ".#.#.", ".#.#.", ".....", ".....", ".....", ".....", ".....")
        g('-', ".....", ".....", ".....", ".###.", ".....", ".....", ".....")
