/**
 * Font a matrice di punti 5×7, come i moduli LED dei tabelloni di stazione.
 * Ogni carattere occupa 5 colonne + 1 colonna di spaziatura ([ADVANCE]).
 */
internal object DotMatrixFont {
    const val COLS = 5
    const val ROWS = 7
    const val ADVANCE = COLS + 1

    /** Larghezza in punti di un testo di [chars] caratteri (senza spaziatura finale). */
    fun widthOf(chars: Int): Int = if (chars <= 0) 0 else chars * ADVANCE - 1

    /**
     * Prepara il testo per il display: maiuscolo e vocali accentate rese come sui
     * tabelloni italiani ("È" -> "E'").
     */
    fun normalize(text: String): String = buildString {
        for (c in text.uppercase()) {
            when (c) {
                'À', 'Á' -> append("A'")
                'È', 'É' -> append("E'")
                'Ì', 'Í' -> append("I'")
                'Ò', 'Ó' -> append("O'")
                'Ù', 'Ú' -> append("U'")
                'Ä' -> append("AE")
                'Ö' -> append("OE")
                'Ü' -> append("UE")
                '’', '‘', '`', '´', '′' -> append('\'')
                '–', '—' -> append('-')
                else -> append(c)
            }
        }
    }

    /** Punti accesi di un testo, in coordinate di griglia (colonna, riga). */
    fun layout(text: String): DotRun {
        val s = normalize(text)
        val xs = ArrayList<Int>(s.length * 12)
        val ys = ArrayList<Int>(s.length * 12)
        s.forEachIndexed { index, c ->
            val rows = glyph(c)
            val x0 = index * ADVANCE
            for (r in 0 until ROWS) {
                val bits = rows[r]
                for (col in 0 until COLS) {
                    if (bits and (1 shl (COLS - 1 - col)) != 0) {
                        xs += x0 + col
                        ys += r
                    }
                }
            }
        }
        return DotRun(widthOf(s.length), xs.toIntArray(), ys.toIntArray())
    }

    fun glyph(c: Char): IntArray = glyphs[c] ?: glyphs.getValue(' ')

    private val glyphs: Map<Char, IntArray> = buildMap {
        fun g(c: Char, vararg rows: String) {
            require(rows.size == ROWS) { "Glyph '$c' must have $ROWS rows" }
            put(c, IntArray(ROWS) { r ->
                rows[r].fold(0) { acc, ch -> (acc shl 1) or if (ch == '#') 1 else 0 }
            })
        }

        g(' ', ".....", ".....", ".....", ".....", ".....", ".....", ".....")

        g('A', ".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#")
        g('B', "####.", "#...#", "#...#", "####.", "#...#", "#...#", "####.")
        g('C', ".###.", "#...#", "#....", "#....", "#....", "#...#", ".###.")
        g('D', "###..", "#..#.", "#...#", "#...#", "#...#", "#..#.", "###..")
        g('E', "#####", "#....", "#....", "####.", "#....", "#....", "#####")
        g('F', "#####", "#....", "#....", "####.", "#....", "#....", "#....")
