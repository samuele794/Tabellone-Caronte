        g('R', "####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#")
        g('S', ".####", "#....", "#....", ".###.", "....#", "....#", "####.")
        g('T', "#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#..")
        g('U', "#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###.")
